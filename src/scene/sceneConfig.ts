/* ============================================================================
 * 场景标定常量
 *
 * 仓库里没有原版 GLB/Blender 源文件，也拿不到。
 * 这里的每一个数都是从参考帧上**量出来**的，
 * 不是「看着差不多」拍的。测量与解算方法记录在下面的注释里，
 * 换素材或改画幅时按同样的方法复核。
 *
 * ── 单位与坐标 ──────────────────────────────────────────────
 * 1 单位 = 一个柜位的宽度。四柜位并排，所以柜体总宽 = 4。
 * 原点 = 柜体底面中心。Y 向上，Z 朝观察者。
 *   x ∈ [-2, +2]、y ∈ [0, H]、z ∈ [-D/2, +D/2]，柜门所在的前平面是 z = +D/2。
 *
 * ── 标定方法 ────────────────────────────────────────────────
 * 从 1.90 / 2.00 / 2.20 / 2.40 / 2.60 / 3.36s 六帧上取柜体轮廓的六个角点
 * （凸包 + 共线点合并），用共享焦距的最小二乘同时解算
 *   焦距 f、柜高 H、柜深 D、每帧的相机方位角/仰角/半径/注视点。
 * 收敛残差 rms 0.87px、最大 2.09px（画幅 1320×724），远小于 3% 的容差。
 * ========================================================================== */

/* ── 柜体几何 ─────────────────────────────────────────────── */

/** 柜位数 */
export const BAY_COUNT = 4
/** 单个柜位宽度 = 1 单位（定义） */
export const BAY_W = 1
/** 柜体总宽 */
export const LOCKER_W = BAY_COUNT * BAY_W
/** 柜体总高。实测 H/W = 0.7054 */
export const LOCKER_H = 2.822
/**
 * 柜体总深。实测 D = 0.540 柜位宽。
 *
 * 注意：一份常见的经验值是「柜深 ≈ 柜位宽 × 0.68」，
 * 那个数是把 2.00s 帧的偏航当成 40° 反推出来的。实际解算出的偏航是 48.3°，
 * 偏航越大同样的侧面投影需要的深度越小，所以真实深度是 0.54 而不是 0.68。
 */
export const LOCKER_D = 0.54

/** 柜体前平面（柜门所在的 z） */
export const FRONT_Z = LOCKER_D / 2
/** 柜体背面 */
export const BACK_Z = -LOCKER_D / 2

/** 柜位中心的 x 坐标，从左到右。第 2 个（index 1）是打开的那个 */
export const BAY_X = Array.from(
  { length: BAY_COUNT },
  (_, i) => -LOCKER_W / 2 + BAY_W * (i + 0.5),
)

/** 打开的柜位序号（从 0 起） */
export const OPEN_BAY = 1

/* ── 相机 ─────────────────────────────────────────────────── */

/**
 * 垂直 FOV。解算出 f = 1436px（724px 画幅高），
 * 即 2·atan(362/1436) = 28.3°，落在 25–35° 的低 FOV 区间。
 */
export const CAMERA_FOV = 28.3
export const CAMERA_NEAR = 0.1
export const CAMERA_FAR = 80

/** 参考画幅：所有参考帧标定都以这个宽高比为准 */
export const REFERENCE_ASPECT = 1320 / 724

