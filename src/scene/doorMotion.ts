/* ============================================================================
 * 柜门运动
 *
 * ── 终点角度是怎么定出来的 ──────────────────────────────────
 * 早先的目标写的是「约 150–160°」，另有一个按
 * 「投影宽/柜位宽 = 0.651」反推的 131°。两个都不对，实测是 **135°**。
 *
 * 在 3.36s 那一帧（相机已落位、解算残差 rms 0.72px）上量：
 *   1. 闭合门的投影宽：bay1 门 240→438px = 198px，bay4 门 880→1072px = 192px
 *   2. 翻开那扇门的**内侧面**投影宽：645→797px = 152px
 *      注意 797→809px 那条是门的**端面厚度**，不能算进门宽，
 *      早先把它算进去会得到 141°，是这次判定里最容易踩的坑
 *   3. 自由边比铰链边高 11%（铰链边 571px / 自由边 636px），
 *      说明自由边离相机近 10%，必须先除掉这层透视放大再反解角度
 *   ⇒ |cos φ| = 152 / (198 × 1.11) = 0.69 → φ ≈ 133°
 *   用同一台相机把门角当未知数直接解自由边屏幕 x：132.7°
 *   用「自由边深度偏移 = 门宽 × sinφ」独立解：138.5°
 *   三条互相独立的量法取中：**135° ± 3°**
 *
 * 反证：同一台相机下 150° 的投影宽是 181px、160° 是 193px，
 * 实测 152px 与它们差 19% 和 27%，远超「门面终点屏幕投影宽度误差 ≤5%」的容差，
 * 所以 150–160° 可以排除。
 *
 * ── 曲线 ────────────────────────────────────────────────────
 * 2.60s 四门全关、2.96s 门已明显过 90°、3.36s 到位。
 * 2.96s 实测门内侧面投影宽 99px，对应约 113°，即 0.84 的行程用掉 0.45 的时间
 * —— easeOutCubic 在 u=0.45 处正好是 0.834，与实测吻合。
 * 门在 t≈1076ms（参考 2.85s）经过 90°，**是真的转过去的**，
 * 不是压扁门宽伪造的侧视（第二条禁令）。
 * ========================================================================== */

import { DOOR_END, DOOR_START } from '../experience/experienceTimeline'

/** 门的终点角度（度）。见文件头的三条独立量法。 */
export const DOOR_OPEN_DEG = 135
export const DOOR_OPEN_RAD = (DOOR_OPEN_DEG * Math.PI) / 180

/** 门经过 90° 侧视状态的时刻 */
export const DOOR_PROFILE_MS =
  DOOR_START + (DOOR_END - DOOR_START) * (1 - Math.cbrt(1 - 90 / DOOR_OPEN_DEG))

function easeOutCubic(x: number): number {
  return 1 - (1 - x) ** 3
}

/** 某个时刻的门角（弧度）。范围外自动钳到闭合 / 到位。 */
export function doorAngleAt(ms: number): number {
  if (ms <= DOOR_START) return 0
  if (ms >= DOOR_END) return DOOR_OPEN_RAD
  const u = (ms - DOOR_START) / (DOOR_END - DOOR_START)
  return DOOR_OPEN_RAD * easeOutCubic(u)
}
