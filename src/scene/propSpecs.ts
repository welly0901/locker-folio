/** 入场缓动。四个批次故意用不同曲线，避免「所有物件统一弹簧弹出」 */
export type EaseName = 'outSine' | 'outCubic' | 'outQuart' | 'outBack'

const EASES: Record<EaseName, (x: number) => number> = {
  outSine: (x) => Math.sin((x * Math.PI) / 2),
  outCubic: (x) => 1 - (1 - x) ** 3,
  outQuart: (x) => 1 - (1 - x) ** 4,
  // 落位过冲 2.2%，只发生一次（对幅度的限制同样适用于物件）
  outBack: (x) => 1 + 1.35 * (x - 1) ** 3 + 0.35 * (x - 1) ** 2,
}

export function easeBy(name: EaseName, x: number): number {
  return EASES[name](x)
}

export type PropSpec = {
  /** 节点名，遵循统一的命名结构 */
  name: string
  url: string
  /**
   * 落位后的锚点世界坐标。
   * `anchor: 'bottom'`（缺省）时 y 是**接触面**的高度——放在隔板上就写隔板上表面的 y，
   * 落地的就写 0。贴片高度是运行时按贴图比例算的，中心点由组件推出来，
   * 这样换素材时不用手工重算「中心 y」。
   * `anchor: 'top'` 用于贴在后壁、按上缘对齐的板子。
   */
  at: readonly [number, number, number]
  anchor?: 'bottom' | 'top' | 'center'
  /** 世界宽度；高度按贴图 alpha 包围盒比例在运行时算 */
  width: number
  /** 绕 Y 轴偏转（弧度），让正面贴片不至于全部正对镜头 */
  yaw?: number
  /** 绕 Z 轴倾斜（弧度），吉他靠柜体时用 */
  roll?: number
  /** 入场起点相对落位点的偏移 */
  from: { dx?: number; dy?: number; dz?: number; scale?: number; yaw?: number }
  /** 入场开始时刻（主时间线毫秒） */
  at_ms: number
  /** 入场时长 */
  dur: number
  ease: EaseName
  /** 是否投影。贴在后壁上的平面不投影，否则会在自己身后糊一片 */
  cast?: boolean
}

